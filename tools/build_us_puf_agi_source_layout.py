#!/usr/bin/env python3
"""Generate the thirteen-field PUF 2015 monetary source projection document.

The accepted twelve-field document
(``us_runtime/puf_2015_monetary_source_projection.json``) and its generator
are **frozen**: the twelve-field kernel hashes its own module bytes into the
artifact store key, and a repository test pins the generator's own sha256 to
that document's ``generation.generator_sha256``. So this is a second generator
that imports the first, proves it is the reviewed one, proves the twelve-field
document still regenerates byte for byte, and then adds exactly one column.

*The one column is reported AGI.* ``E00100`` is a delivered publisher amount
field at delivered index 73, publisher position 31, printed with the ``(+/-)``
marker. It is decoded under the same grammar, the same disclosure-aggregate
lexical split and the same amount-universe rule as the other twelve. Nothing
computes AGI, and no component identity between AGI and the twelve projected
amounts is asserted: the booklets state none, and the column carries that as
an explicit unresolved entry.

*Why the earlier source-only rationale no longer applies.* The frozen
generator lists ``E00100`` under ``notable_source_only`` because "the reviewed
growth slice already retains source-year AGI as provenance". Reading the
growth slice
(:mod:`microcosm.build.us_runtime.puf_growth`), that provenance column is a
*copy of the growth transform's own input* ``E00100``, not an independent
source of AGI, and the recipe contract requires ``E00100`` as a declared money
field. Without a projected ``E00100`` there is no AGI at all on this path, so
projecting it creates the only source rather than a second competing one. The
supersession is recorded in the emitted document.

Usage::

    python tools/build_us_puf_agi_source_layout.py --documents-dir DIR --write
    python tools/build_us_puf_agi_source_layout.py --documents-dir DIR --verify
"""

from __future__ import annotations

import argparse
import contextlib
import hashlib
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARENT_TOOL = ROOT / "tools/build_us_puf_source_layout.py"
PACKAGE = ROOT / "packages/microcosm-build/src/microcosm/build"
PARENT_OUTPUT = PACKAGE / "us_runtime/puf_2015_monetary_source_projection.json"
OUTPUT = PACKAGE / "us_runtime/puf_2015_monetary_agi_source_projection.json"

#: The one field this edition adds, and everything about it that is a choice.
AGI_FIELD = "E00100"
AGI_CONCEPT = "adjusted_gross_income_deficit"
AGI_CONCEPT_GROUP = "adjusted_gross_income"
EDITION = "thirteen_field_reported_agi"


class GenerationError(RuntimeError):
    """The extension refuses rather than emitting an unauthenticated document."""


def load_parent():
    """Import the frozen generator and prove it is the reviewed one."""
    packaged = json.loads(PARENT_OUTPUT.read_text(encoding="utf-8"))
    pinned = packaged["generation"]["generator_sha256"]
    actual = hashlib.sha256(PARENT_TOOL.read_bytes()).hexdigest()
    if actual != pinned:
        raise GenerationError(
            "the parent generator is not the one the packaged twelve-field "
            f"document was generated by ({actual} != {pinned})"
        )
    name = "_us_puf_source_layout_frozen"
    cached = sys.modules.get(name)
    if cached is not None:
        return cached, packaged, pinned
    spec = importlib.util.spec_from_file_location(name, PARENT_TOOL)
    module = importlib.util.module_from_spec(spec)
    # ``dataclasses`` resolves a class's defining module through
    # ``sys.modules``, so the module has to be registered before it executes.
    sys.modules[name] = module
    try:
        spec.loader.exec_module(module)
    except BaseException:
        del sys.modules[name]
        raise
    return module, packaged, pinned


def agi_entry(parent):
    """The ``E00100`` projection specification, in the parent's own vocabulary."""
    return parent.Projected(
        AGI_FIELD,
        AGI_CONCEPT,
        AGI_CONCEPT_GROUP,
        unresolved=(
            (
                "component_identity_with_the_projected_amounts",
                "Neither booklet states that reported AGI equals any sum or "
                "difference of the twelve projected columns, and the "
                "publisher's rebalancing edit is not documented as preserving "
                "such an identity. AGI is retained as its own delivered "
                "column; nothing here computes, checks or repairs an "
                "accounting relationship between it and the components.",
            ),
            (
                "deficit_sign_semantics",
                "The record layout prints the (+/-) marker, so negative "
                "values are documented, but the booklets do not define which "
                "deductions a negative AGI reflects. The sign is preserved "
                "and never interpreted.",
            ),
        ),
        notes=(
            "Reported adjusted gross income as delivered. This is the "
            "publisher's own edited AGI field, not a quantity derived from "
            "the other projected columns and not a tax outcome recomputed "
            "under any year's law.",
        ),
    )


@contextlib.contextmanager
def extended_parent(parent, entry):
    """Add one column to the frozen module's declarations, then put them back.

    ``load_parent`` hands back a **cached** module, so an assignment to
    ``parent.PROJECTION`` outlives the call that made it. Without this restore
    a second :func:`build_document` in the same process starts from thirteen
    declarations: the twelve-field regeneration then produces thirteen
    columns, and the mismatch is reported as "the parent generator no longer
    reproduces the packaged twelve-field document" — a serious claim about the
    accepted artifact, raised by this file's own leftover state rather than by
    anything wrong with the parent.

    The restore is in a ``finally``, so a refusal raised inside the block
    leaves the module unedited too. That matters more than the success path: a
    caller that catches one :class:`GenerationError` and retries would
    otherwise get a second, different and untrue one.

    Args:
        parent: The imported frozen generator module.
        entry: The ``Projected`` entry to append, in the parent's vocabulary.

    Yields:
        ``None``, with the parent's declarations extended for the block.
    """
    projection = parent.PROJECTION
    notable = parent.NOTABLE_SOURCE_ONLY
    parent.PROJECTION = (*projection, entry)
    parent.NOTABLE_SOURCE_ONLY = {
        name: text for name, text in notable.items() if name != AGI_FIELD
    }
    try:
        yield
    finally:
        parent.PROJECTION = projection
        parent.NOTABLE_SOURCE_ONLY = notable


def build_document(documents_dir: Path) -> dict[str, object]:
    parent, packaged, parent_generator_sha256 = load_parent()

    # The twelve-field document must still regenerate exactly, so this
    # extension provably starts from the accepted bytes.
    twelve = parent.build_document(documents_dir)
    twelve_bytes = parent.canonical_bytes(twelve) + b"\n"
    if twelve_bytes != PARENT_OUTPUT.read_bytes():
        raise GenerationError(
            "the parent generator no longer reproduces the packaged "
            "twelve-field document"
        )
    twelve_fields = [column["field"] for column in twelve["projection"]["columns"]]
    if AGI_FIELD in twelve_fields:
        raise GenerationError(f"{AGI_FIELD} is already projected upstream")

    superseded = parent.NOTABLE_SOURCE_ONLY.get(AGI_FIELD)
    if superseded is None:
        raise GenerationError(f"{AGI_FIELD} is not annotated source-only upstream")

    # Extend the frozen module's own declarations rather than restating them,
    # for exactly the one call that needs them extended.
    with extended_parent(parent, agi_entry(parent)):
        document = parent.build_document(documents_dir)

    fields = [column["field"] for column in document["projection"]["columns"]]
    if fields != sorted(
        [*twelve_fields, AGI_FIELD],
        key=lambda name: next(
            column["delivered_index"]
            for column in document["layout"]["main"]["columns"]
            if column["name"] == name
        ),
    ):
        raise GenerationError("the thirteen-field column order is not delivered order")
    if document["projection"]["column_count"] != 13:
        raise GenerationError("the extension did not produce thirteen columns")
    if (
        document["layout"]["not_selected_reasons"]
        != twelve["layout"]["not_selected_reasons"]
    ):
        raise GenerationError("the not-selected vocabulary moved")
    for key in (
        "anchors",
        "booklets",
        "refused_fields",
        "refused_derivations",
        "source_conflicts",
        "sources",
        "raw_source_definition",
    ):
        if document[key] != twelve[key]:
            raise GenerationError(f"the extension changed {key}")

    document["projection_edition"] = {
        "edition": EDITION,
        "adds": [AGI_FIELD],
        "parent_document_sha256": hashlib.sha256(twelve_bytes).hexdigest(),
        "parent_document_canonical_sha256": hashlib.sha256(
            parent.canonical_bytes(twelve)
        ).hexdigest(),
        "parent_projected_fields": twelve_fields,
        "parent_generator_sha256": parent_generator_sha256,
        "preserves": (
            "The twelve-field document, its artifact type "
            "microcosm.us.puf_2015_monetary_source_projection/3, its kernel "
            "and its store key are untouched. This edition is a separate "
            "document behind a separate artifact type."
        ),
        "supersedes_notable_source_only": {
            AGI_FIELD: {
                "upstream_statement": superseded,
                "why_it_no_longer_applies": (
                    "The growth slice's puf_source_year_agi column is a copy "
                    "of that transform's own input E00100, not an independent "
                    "AGI source, and GrowthRecipe requires E00100 as a "
                    "declared money field. Without this column there is no "
                    "AGI on the projection path at all, so projecting it is "
                    "the only source rather than a second competing one."
                ),
            }
        },
        "not_derived": (
            "E00100 is the delivered reported field. No AGI is computed, "
            "reconstructed from components, or reconciled against them."
        ),
    }
    document["generation"] = {
        "generator": "tools/build_us_puf_agi_source_layout.py",
        "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "parent_generator": "tools/build_us_puf_source_layout.py",
        "parent_generator_sha256": parent_generator_sha256,
        "reads": [
            "the three pinned booklet text extractions",
            "the packaged raw source definition",
            "the packaged twelve-field projection document",
        ],
        "reads_microdata": False,
    }
    return document


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--documents-dir", type=Path, required=True)
    parser.add_argument("--receipt", type=Path)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args(argv)
    module, _, _ = load_parent()
    document = build_document(args.documents_dir)
    payload = module.canonical_bytes(document) + b"\n"
    if args.write:
        OUTPUT.write_bytes(payload)
        print(f"wrote {OUTPUT} ({len(payload)} bytes)")
    if args.verify:
        current = OUTPUT.read_bytes() if OUTPUT.exists() else b""
        if current != payload:
            print("REGENERATED DOCUMENT DIFFERS FROM THE PACKAGED BYTES")
            return 1
        print(f"verified {OUTPUT} ({len(payload)} bytes)")
    if args.receipt:
        args.receipt.write_text(
            json.dumps(
                {
                    "interpreter_version": sys.version.split()[0],
                    "generator_sha256": document["generation"]["generator_sha256"],
                    "parent_generator_sha256": document["generation"][
                        "parent_generator_sha256"
                    ],
                    "documents_dir": str(args.documents_dir.resolve()),
                    "document_sha256": hashlib.sha256(payload).hexdigest(),
                    "document_bytes": len(payload),
                    "verified_packaged_bytes": args.verify,
                    "microdata_read": False,
                },
                indent=2,
            )
            + "\n"
        )
    print(
        json.dumps(
            {
                "projected_columns": document["projection"]["column_count"],
                "fields": [c["field"] for c in document["projection"]["columns"]],
                "sha256": hashlib.sha256(payload).hexdigest(),
                "bytes": len(payload),
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":  # pragma: no cover - script entry point
    raise SystemExit(main())
