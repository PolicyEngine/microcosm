"""HMRC's property rental income statistics, typed from the pinned Chronicle feed.

HMRC's Property Rental Income Statistics (PRIS, 2026 release) describe
unincorporated landlords from the Self Assessment property pages for tax year
2024-25: how many there are, their rental income, their allowable expenses
by type, and how many fall in each band of rental income. HMRC confirmed that
the published income is **before** allowable expenses (microcosm#1106), so it
is the landlords' receipts, and receipts less expenses is a derived cell. The
expense table lists residential finance costs beside the deductible expenses,
although ITTOIA 2005 s. 272A no longer deducts them: they are relieved as a
tax reduction (s. 274A) instead.

Every row is copied verbatim from the pinned Chronicle consumer feed into one
vendored resource (``hmrc_property_rental_income_facts.json``, regenerated by
``tools/vendor_uk_ledger_facts.py``): Table 1 (landlords by type of tax
entity), Table 2 (rental income by type of tax entity), Table 6 (allowable
expenses by type of tax entity), Table 8 (allowable expenses by type) and
Table 13 (landlords by size of rental income). The loader types those rows,
refuses a resource that was not vendored from the committed feed pin or from
the pinned workbook, and refuses a roster that has drifted from the module
constants.

Read the basis before using these facts. Tables 1, 2 and 6 split individuals
from partnerships; Tables 8 and 13 count every tax entity, partnerships
included, so a consumer that needs them on the individuals basis declares the
translation (the individuals' share of landlords from Table 1, of expenses
from Table 6). Counts publish in millions to two decimals (Table 13 to the
nearest 10,000) and amounts in billions of pounds to two decimals; the feed
carries both in people and pounds.
"""

from __future__ import annotations

import hashlib
from collections.abc import Mapping
from dataclasses import dataclass
from importlib.resources import files
from typing import Any

from microcosm.build.uk_runtime.ledger_fact_vendoring import (
    load_vendored_resource,
    verify_vendored_resource_feed_identity,
)

__all__ = [
    "HMRC_PROPERTY_RENTAL_EXPENSE_TYPES",
    "HMRC_PROPERTY_RENTAL_RECEIPTS_BAND_LOWER_BOUNDS",
    "HMRC_PROPERTY_RENTAL_RECORD_SETS",
    "HMRC_PROPERTY_RENTAL_RESIDENTIAL_FINANCE_COSTS",
    "HMRC_PROPERTY_RENTAL_RESOURCE",
    "HMRC_PROPERTY_RENTAL_SOURCE_FILE",
    "HMRC_PROPERTY_RENTAL_SOURCE_SHA256",
    "HMRC_PROPERTY_RENTAL_TAX_YEAR",
    "HMRCPropertyRentalBand",
    "HMRCPropertyRentalFacts",
    "load_hmrc_property_rental_facts",
]

#: The per-concern vendored resource; never edited by hand.
HMRC_PROPERTY_RENTAL_RESOURCE = "hmrc_property_rental_income_facts.json"

#: Tax year (start year) of every row: 2024-25, the build period's tax year.
HMRC_PROPERTY_RENTAL_TAX_YEAR = 2024

#: The publisher workbook every vendored row must trace back to. A resource
#: re-vendored from a later release fails on this pin, so revised statistics
#: are a reviewed change.
HMRC_PROPERTY_RENTAL_SOURCE_FILE = "property_rental_income_statistics_tables_2026.ods"
HMRC_PROPERTY_RENTAL_SOURCE_SHA256 = (
    "87627fbf6122a88f9d20ce7c98d31c103d423fb10d66d661d87324d67227c846"
)

_TABLE1_RECORD_SET_ID = "hmrc.property_rental_2026.table_1.ty2024"
_TABLE2_RECORD_SET_ID = "hmrc.property_rental_2026.table_2.ty2024"
_TABLE6_RECORD_SET_ID = "hmrc.property_rental_2026.table_6.ty2024"
_TABLE8_RECORD_SET_ID = "hmrc.property_rental_2026.table_8.ty2024"
_TABLE13_RECORD_SET_ID = "hmrc.property_rental_2026.table_13.ty2024"

#: Every Chronicle record set the stage reads from the vendored resource, as
#: the manifests' ``verify_vendored_fact_resource`` operation declares them.
HMRC_PROPERTY_RENTAL_RECORD_SETS: tuple[str, ...] = (
    _TABLE1_RECORD_SET_ID,
    _TABLE2_RECORD_SET_ID,
    _TABLE6_RECORD_SET_ID,
    _TABLE8_RECORD_SET_ID,
    _TABLE13_RECORD_SET_ID,
)

#: Lower bound of each Table 13 band of rental income, in pounds. The top
#: band is open.
HMRC_PROPERTY_RENTAL_RECEIPTS_BAND_LOWER_BOUNDS: tuple[int, ...] = (
    0,
    10_000,
    20_000,
    30_000,
    40_000,
    50_000,
    60_000,
    70_000,
    80_000,
    90_000,
    100_000,
)

#: The Table 8 expense types, all tax entities. Non-residential finance costs
#: stay deductible; only residential (dwelling-related) finance costs are
#: restricted.
HMRC_PROPERTY_RENTAL_RESIDENTIAL_FINANCE_COSTS = "residential_finance_costs"
HMRC_PROPERTY_RENTAL_EXPENSE_TYPES: tuple[str, ...] = (
    "rent_rates_and_insurance",
    "repairs_and_maintenance",
    HMRC_PROPERTY_RENTAL_RESIDENTIAL_FINANCE_COSTS,
    "non_residential_finance_costs",
    "legal_management_and_professional_fees",
    "services_including_wages",
    "other_allowable_expenses",
)

_ENTITY_TYPES = ("individual", "partnership")
_UK_GEOGRAPHY_ID = "K02000001"
#: Table 8's types sum to Table 6's all-entity total up to the publication's
#: rounding (seven amounts each rounded to GBP 10m).
_EXPENSE_TOTAL_ROUNDING_GBP = 7 * 5_000_000.0


@dataclass(frozen=True)
class HMRCPropertyRentalBand:
    """One Table 13 row: tax entities by size of rental income."""

    lower_bound: int
    upper_bound: int | None
    landlords: float


@dataclass(frozen=True)
class HMRCPropertyRentalFacts:
    """The 2024-25 PRIS rows the property components stage reads."""

    tax_year: int
    #: Tables 1, 2 and 6 by type of tax entity: ``individual``,
    #: ``partnership`` and ``all``.
    landlords: Mapping[str, float]
    receipts: Mapping[str, float]
    expenses: Mapping[str, float]
    #: Table 8 amounts and landlord counts by expense type, all tax entities.
    expenses_by_type: Mapping[str, float]
    expense_landlords_by_type: Mapping[str, float]
    #: Table 13, all tax entities, lowest band first.
    receipts_bands: tuple[HMRCPropertyRentalBand, ...]
    resource_sha256: str

    def individuals_share(self, measure: str) -> float:
        """Individuals ÷ all tax entities for ``landlords``, ``receipts`` or
        ``expenses`` (Tables 1, 2 and 6)."""

        values = getattr(self, measure)
        total = float(values["all"])
        if total <= 0.0:
            raise ValueError(f"PRIS all-entity {measure} must be positive.")
        return float(values["individual"]) / total

    def individuals_receipts_bands(self) -> tuple[HMRCPropertyRentalBand, ...]:
        """Table 13 on the individuals basis.

        Declared translation: every band is scaled by the individuals' share
        of landlords (Table 1), on the assumption that partnerships spread
        across bands like all tax entities. Partnerships' mean receipts are
        several times individuals', so the assumption overstates the
        individuals in the top bands; the stage receipt records it.
        """

        share = self.individuals_share("landlords")
        return tuple(
            HMRCPropertyRentalBand(
                band.lower_bound, band.upper_bound, band.landlords * share
            )
            for band in self.receipts_bands
        )

    def individuals_residential_finance_costs(self) -> float:
        """Table 8's residential finance costs scaled by the individuals'
        share of expenses (Table 6), the declared translation."""

        return float(
            self.expenses_by_type[HMRC_PROPERTY_RENTAL_RESIDENTIAL_FINANCE_COSTS]
        ) * self.individuals_share("expenses")

    def individuals_deductible_expenses(self) -> float:
        """Individuals' allowable expenses other than residential finance
        costs: the expenses that separate receipts from the SPI's profit."""

        return float(self.expenses["individual"]) - (
            self.individuals_residential_finance_costs()
        )

    def evidence(self) -> dict[str, object]:
        return {
            "resource": HMRC_PROPERTY_RENTAL_RESOURCE,
            "resource_sha256": self.resource_sha256,
            "tax_year": self.tax_year,
            "landlords": dict(self.landlords),
            "receipts_gbp": dict(self.receipts),
            "expenses_gbp": dict(self.expenses),
            "expenses_by_type_gbp": dict(self.expenses_by_type),
            "individuals_share": {
                measure: self.individuals_share(measure)
                for measure in ("landlords", "receipts", "expenses")
            },
            "individuals_residential_finance_costs_gbp": (
                self.individuals_residential_finance_costs()
            ),
            "individuals_deductible_expenses_gbp": (
                self.individuals_deductible_expenses()
            ),
            "receipts_bands": [
                {
                    "lower_bound": band.lower_bound,
                    "upper_bound": band.upper_bound,
                    "landlords": band.landlords,
                }
                for band in self.receipts_bands
            ],
        }


def _rows(payload: Mapping[str, Any], record_set_id: str) -> list[Mapping[str, Any]]:
    rows = [
        row
        for row in payload["rows"]
        if (row.get("layout") or {}).get("record_set_id") == record_set_id
    ]
    if not rows:
        raise ValueError(
            f"{HMRC_PROPERTY_RENTAL_RESOURCE} carries no {record_set_id} rows."
        )
    for row in rows:
        source = row.get("source") or {}
        if (
            source.get("source_file") != HMRC_PROPERTY_RENTAL_SOURCE_FILE
            or source.get("source_sha256") != HMRC_PROPERTY_RENTAL_SOURCE_SHA256
        ):
            raise ValueError(
                f"{record_set_id} row {row.get('aggregate_fact_key')} does not "
                f"trace to {HMRC_PROPERTY_RENTAL_SOURCE_FILE} at the pinned sha256."
            )
        period = row.get("period") or {}
        if period.get("type") != "tax_year" or int(period.get("value", -1)) != int(
            HMRC_PROPERTY_RENTAL_TAX_YEAR
        ):
            raise ValueError(f"{record_set_id} carries a row outside tax year 2024.")
        if (row.get("geography") or {}).get("id") != _UK_GEOGRAPHY_ID:
            raise ValueError(f"{record_set_id} carries a row outside the UK.")
    return rows


def _by_entity_type(rows: list[Mapping[str, Any]], *, label: str) -> dict[str, float]:
    values: dict[str, float] = {}
    for row in rows:
        key = str((row.get("dimensions") or {}).get("tax_entity_type", "all"))
        if key in values:
            raise ValueError(f"{label} repeats tax entity type {key!r}.")
        values[key] = float(row["value"])
    if set(values) != {*_ENTITY_TYPES, "all"}:
        raise ValueError(f"{label} must carry individuals, partnerships and all.")
    if abs(values["individual"] + values["partnership"] - values["all"]) > max(
        0.011 * values["all"], 1.0
    ):
        raise ValueError(f"{label}: individuals and partnerships do not sum to all.")
    return values


def load_hmrc_property_rental_facts(
    resource: str = HMRC_PROPERTY_RENTAL_RESOURCE,
    *,
    verify_feed_identity: bool = True,
) -> HMRCPropertyRentalFacts:
    """Type the vendored PRIS 2024-25 rows; refuse drift by name."""

    payload = load_vendored_resource(resource)
    if verify_feed_identity:
        verify_vendored_resource_feed_identity(payload)
    digest = hashlib.sha256(
        files("microcosm.build.uk").joinpath(resource).read_bytes()
    ).hexdigest()
    landlords = _by_entity_type(_rows(payload, _TABLE1_RECORD_SET_ID), label="Table 1")
    receipts = _by_entity_type(_rows(payload, _TABLE2_RECORD_SET_ID), label="Table 2")
    expenses = _by_entity_type(_rows(payload, _TABLE6_RECORD_SET_ID), label="Table 6")

    amounts: dict[str, float] = {}
    counts: dict[str, float] = {}
    for row in _rows(payload, _TABLE8_RECORD_SET_ID):
        kind = (row.get("dimensions") or {}).get("property_expense_type")
        if kind is None:
            continue
        measure = str(row.get("measure_id", ""))
        target = {
            "property_expenses_amount": amounts,
            "expenses_landlord_count": counts,
        }.get(measure)
        if target is None:
            continue
        if kind in target:
            raise ValueError(f"Table 8 repeats {kind!r} for {measure!r}.")
        target[str(kind)] = float(row["value"])
    if tuple(sorted(amounts)) != tuple(sorted(HMRC_PROPERTY_RENTAL_EXPENSE_TYPES)):
        raise ValueError(
            "Table 8 expense types drifted from the module roster: "
            f"{sorted(amounts)} against {sorted(HMRC_PROPERTY_RENTAL_EXPENSE_TYPES)}."
        )
    if abs(sum(amounts.values()) - expenses["all"]) > _EXPENSE_TOTAL_ROUNDING_GBP:
        raise ValueError(
            "Table 8's expense types do not sum to Table 6's all-entity "
            f"expenses: {sum(amounts.values()):.0f} against {expenses['all']:.0f}."
        )

    bands: list[HMRCPropertyRentalBand] = []
    for row in _rows(payload, _TABLE13_RECORD_SET_ID):
        dimensions = row.get("dimensions") or {}
        lower = int(dimensions.get("property_income_lower_bound", 0))
        upper = dimensions.get("property_income_upper_bound")
        bands.append(
            HMRCPropertyRentalBand(
                lower, None if upper is None else int(upper), float(row["value"])
            )
        )
    bands.sort(key=lambda band: band.lower_bound)
    lowers = tuple(band.lower_bound for band in bands)
    if lowers != HMRC_PROPERTY_RENTAL_RECEIPTS_BAND_LOWER_BOUNDS:
        raise ValueError(
            f"Table 13 bands drifted from the module roster: {lowers} against "
            f"{HMRC_PROPERTY_RENTAL_RECEIPTS_BAND_LOWER_BOUNDS}."
        )
    for band, following in zip(bands, bands[1:], strict=False):
        if band.upper_bound != following.lower_bound:
            raise ValueError("Table 13 bands must be contiguous.")
    if bands[-1].upper_bound is not None:
        raise ValueError("Table 13's top band must be open.")
    return HMRCPropertyRentalFacts(
        tax_year=HMRC_PROPERTY_RENTAL_TAX_YEAR,
        landlords=landlords,
        receipts=receipts,
        expenses=expenses,
        expenses_by_type=amounts,
        expense_landlords_by_type=counts,
        receipts_bands=tuple(bands),
        resource_sha256=digest,
    )
