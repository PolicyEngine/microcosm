def _joint_rows(rows: list[Mapping[str, Any]]) -> list[Mapping[str, Any]]:
    return [
        row
        for row in rows
        if _record_set_id(row).startswith(HMRC_CGT_JOINT_RECORD_SET_PREFIX)
    ]


def _parse_joint(
    rows: list[Mapping[str, Any]],
) -> tuple[
    tuple[HMRCCapitalGainsCell, ...],
    tuple[HMRCCapitalGainsBandTotal, ...],
    tuple[HMRCCapitalGainsIncomeTotal, ...],
    float,
    float,
    tuple[str, str],
]:
    """Type the Table 3 rows and refuse a roster or source that has drifted."""

    joint_rows = _joint_rows(rows)
    if not joint_rows:
        raise ValueError(
            f"{HMRC_CGT_SOURCE_LABEL}: no vendored rows under record set prefix "
            f"{HMRC_CGT_JOINT_RECORD_SET_PREFIX!r}."
        )
    sources = {
        (
            str((row.get("source") or {}).get("source_file") or ""),
            str((row.get("source") or {}).get("source_sha256") or ""),
        )
        for row in joint_rows
    }
    if sources != {(HMRC_CGT_JOINT_SOURCE_FILE, HMRC_CGT_JOINT_SOURCE_SHA256)}:
        raise ValueError(
            f"{HMRC_CGT_SOURCE_LABEL}: vendored rows trace to {sorted(sources)}, "
            f"not the pinned {HMRC_CGT_JOINT_SOURCE_FILE} "
            f"({HMRC_CGT_JOINT_SOURCE_SHA256})."
        )

    cells: dict[tuple[int, int], dict[str, float]] = {}
    gain_bounds: dict[int, int | None] = {}
    income_bounds: dict[int, int | None] = {}
    band_totals: dict[int, dict[str, float]] = {}
    income_totals: dict[int, dict[str, float]] = {}
    grand: dict[str, float] = {}
    for row in joint_rows:
        measure_id = _measure_id(row)
        kind, _, column = measure_id.partition("_")
        if kind not in _JOINT_MEASURES or not column:
            raise ValueError(
                f"{HMRC_CGT_SOURCE_LABEL}: unexpected measure {measure_id!r}."
            )
        measure = _JOINT_MEASURES[kind]
        dimensions = row.get("dimensions") or {}
        gain_value = dimensions.get("cgt_gain_band")
        income_value = dimensions.get("cgt_taxable_income_band")
        gain_lower: int | None = None
        income_lower: int | None = None
        if gain_value is not None:
            gain_lower, gain_upper = _band_bounds_from_value_id(
                str(gain_value), prefix="gain"
            )
            gain_bounds.setdefault(gain_lower, gain_upper)
        if income_value is not None:
            income_lower, income_upper = _band_bounds_from_value_id(
                str(income_value), prefix="income"
            )
            income_bounds.setdefault(income_lower, income_upper)
            if column != str(income_value):
                raise ValueError(
                    f"{HMRC_CGT_SOURCE_LABEL}: measure {measure_id!r} disagrees "
                    f"with its income band {income_value!r}."
                )
        elif column != _ALL_INCOMES_COLUMN:
            raise ValueError(
                f"{HMRC_CGT_SOURCE_LABEL}: measure {measure_id!r} carries no "
                "income band."
            )
        value = _value(row)
        if gain_lower is not None and income_lower is not None:
            target = cells.setdefault((gain_lower, income_lower), {})
        elif gain_lower is not None:
            target = band_totals.setdefault(gain_lower, {})
        elif income_lower is not None:
            target = income_totals.setdefault(income_lower, {})
        else:
            target = grand
        if measure in target:
            raise ValueError(
                f"{HMRC_CGT_SOURCE_LABEL}: duplicate {measure!r} row for gains "
                f"from {gain_lower} and income from {income_lower}."
            )
        target[measure] = value

    gains = tuple(sorted(gain_bounds))
    if gains != HMRC_CGT_GAIN_BAND_LOWER_BOUNDS:
        raise ValueError(
            f"{HMRC_CGT_SOURCE_LABEL}: gain-band roster drifted: expected "
            f"{HMRC_CGT_GAIN_BAND_LOWER_BOUNDS}, got {gains}."
        )
    incomes = tuple(sorted(income_bounds))
    if incomes != HMRC_CGT_INCOME_BAND_LOWER_BOUNDS:
        raise ValueError(
            f"{HMRC_CGT_SOURCE_LABEL}: income-band roster drifted: expected "
            f"{HMRC_CGT_INCOME_BAND_LOWER_BOUNDS}, got {incomes}."
        )
    for bounds, label in ((gain_bounds, "gain"), (income_bounds, "income")):
        ordered = sorted(bounds)
        for earlier, later in zip(ordered, ordered[1:], strict=False):
            if bounds[earlier] != later:
                raise ValueError(
                    f"{HMRC_CGT_SOURCE_LABEL}: {label} bands are not contiguous "
                    f"at {earlier}."
                )
        if bounds[ordered[-1]] is not None:
            raise ValueError(f"{HMRC_CGT_SOURCE_LABEL}: top {label} band must be open.")

    typed_cells = tuple(
        HMRCCapitalGainsCell(
            gain_lower_bound=gain_lower,
            income_lower_bound=income_lower,
            individuals=cells.get((gain_lower, income_lower), {}).get("individuals"),
            gains=cells.get((gain_lower, income_lower), {}).get("gains"),
        )
        for gain_lower in gains
        for income_lower in incomes
    )
    typed_band_totals = []
    for gain_lower in gains:
        total = band_totals.get(gain_lower, {})
        if "gains" not in total:
            raise ValueError(
                f"{HMRC_CGT_SOURCE_LABEL}: the all-incomes amount for gains from "
                f"{gain_lower} is missing, which is unexpected."
            )
        typed_band_totals.append(
            HMRCCapitalGainsBandTotal(
                gain_lower_bound=gain_lower,
                individuals=total.get("individuals"),
                gains=total["gains"],
            )
        )
    typed_income_totals = tuple(
        HMRCCapitalGainsIncomeTotal(
            income_lower_bound=income_lower,
            individuals=income_totals.get(income_lower, {}).get("individuals"),
            gains=income_totals.get(income_lower, {}).get("gains"),
        )
        for income_lower in incomes
    )
    if "individuals" not in grand or "gains" not in grand:
        raise ValueError(
            f"{HMRC_CGT_SOURCE_LABEL}: the all-gains, all-incomes pair is missing."
        )
    total_individuals = grand["individuals"]
    total_gains = grand["gains"]
    if (
        total_individuals != HMRC_CGT_TOTAL_INDIVIDUALS
        or total_gains != HMRC_CGT_TOTAL_GAINS_GBP
    ):
        raise ValueError(
            f"{HMRC_CGT_SOURCE_LABEL}: published totals drifted: "
            f"{total_individuals} individuals and {total_gains} of gains, not "
            f"the pinned {HMRC_CGT_TOTAL_INDIVIDUALS} and {HMRC_CGT_TOTAL_GAINS_GBP}."
        )
    # Cells can only sum to less than the published total, by whatever sits
    # inside suppressed cells. Summing to more means the rows are wrong.
    summed_gains = sum(cell.gains for cell in typed_cells if cell.gains is not None)
    if summed_gains > total_gains + _AMOUNT_RECONCILIATION_TOLERANCE:
        raise ValueError(
            f"{HMRC_CGT_SOURCE_LABEL}: cells sum to {summed_gains} of gains, "
            f"above the published total of {total_gains}."
        )
    return (
        typed_cells,
        tuple(typed_band_totals),
        typed_income_totals,
        total_individuals,
        total_gains,
        (HMRC_CGT_JOINT_SOURCE_FILE, HMRC_CGT_JOINT_SOURCE_SHA256),
    )


def load_hmrc_cgt_joint_distribution(
    resource: str = HMRC_CGT_CONDITIONING_RESOURCE,
    *,
    verify_feed_identity: bool = True,
) -> HMRCCapitalGainsJointDistribution:
    """Read the 2024-25 joint distribution of gains by taxable income.

    Args:
        resource: The vendored resource carrying the Table 3 rows.
        verify_feed_identity: Whether to require the resource to record the
            committed Chronicle feed pin. Only a diagnostic caller reading a
            resource vendored from another feed turns this off, and it then
            owns what it read.

    Raises:
        ValueError: If the resource was not vendored from the pinned feed,
            its rows do not trace to the pinned publisher workbook, or the
            band roster and published totals differ from what this module
            was written against.
    """

    payload, digest = _load_resource(
        resource, verify_feed_identity=verify_feed_identity
    )
    cells, band_totals, income_totals, total_individuals, total_gains, source = (
        _parse_joint(list(payload["rows"]))
    )
    return HMRCCapitalGainsJointDistribution(
        cells=cells,
        band_totals=band_totals,
        income_totals=income_totals,
        source=HMRCCapitalGainsSourceProvenance(
            resource=resource,
            resource_sha256=digest,
            source_commit=str(payload["source_fact_feed"]["source_commit"]),
            record_set_prefix=HMRC_CGT_JOINT_RECORD_SET_PREFIX,
            source_file=source[0],
            source_sha256=source[1],
            source_vintage=HMRC_CGT_SOURCE_VINTAGE,
            build_period=HMRC_CGT_BUILD_PERIOD,
        ),
        total_individuals=total_individuals,
        total_gains=total_gains,
    )
