"""HMRC's published capital gains surfaces, typed from the pinned Chronicle feed.

The FRS does not ask about capital gains, so a UK build has to impute them.
What it imputes against decides whether the result can answer a capital gains
question at all: the tax is held by very few people, with roughly 3,000
taxpayers above £5m of gains holding £48.5bn of them in 2024-25, so a source
that cannot reach those bands produces a population whose total is right and
whose shape is wrong.

HMRC Table 3 publishes the joint distribution directly — individuals and
gains by size of gain crossed with taxable income — which is the surface an
imputation conditioned on income needs, and it carries the top bands. The
2026 release publishes it for 2024-25, the same tax year as the Table 1
observations the calibration fits, so the joint is read at that vintage and
no year is aged forward.

Every row here is copied verbatim from the pinned Chronicle consumer feed
into one vendored resource (``hmrc_cgt_conditioning_facts.json``,
regenerated by ``tools/vendor_uk_ledger_facts.py``): Table 3 (the joint),
Table 2.1a (size of gain), Table 6 (age), Table 5 (country and region) and
Table 1 (individuals, trusts and their total). The loaders type those rows,
refuse a resource that was not vendored from the committed feed pin, and
refuse a roster that has drifted from the module constants, so a re-vendored
resource whose publisher shape moved fails here rather than allocating to
the wrong cells.

Read the published basis before using these facts. Gains are after losses and
attributed gains but **before** the annual exempt amount. Taxable income is
after reliefs and the personal allowance. Trusts are excluded from Tables 2.1a,
3 and 6, and only individuals with a CGT liability appear at all, which is why
the joint shows relatively few people below £10,000 of gains rather than the
many people whose gains fall under the exempt amount. Table 5 covers all
taxpayers including trusts; Table 1 carries the individuals/total shares that
restate it on the individuals basis.

Counts publish in thousands and amounts in £ millions; the feed carries both
in people and pounds. Cells too small to publish are absent from the feed
and come back as ``None`` rather than zero — counts publish in thousands, so
a suppressed count means "fewer than 1,000 people", not "nobody".
"""

