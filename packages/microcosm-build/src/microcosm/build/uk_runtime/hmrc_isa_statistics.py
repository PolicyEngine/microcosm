class HMRCISAStatisticsError(ValueError):
    """Raised when the vendored ISA facts do not carry the published roster."""


@dataclass(frozen=True)
class HMRCISABand:
    """One published band: ``lower < x <= upper`` (``upper is None`` is open).

    The exact GBP 20,000 band is ``lower == upper == 20000``; a lower bound is
    exclusive, so the first income band (GBP 0 to 12,570) carries ``lower = None``.
    """

    value_id: str
    lower: float | None
    upper: float | None

    @property
    def is_point(self) -> bool:
        return self.lower is not None and self.lower == self.upper


def isa_band_bounds(value_id: str) -> tuple[int, int | None]:
    """Parse ``<prefix>_<lo>_to_<hi>`` or ``<prefix>_<lo>_plus`` into published edges."""

    match = re.fullmatch(r"[a-z_]+?_(\d+)_to_(\d+)", value_id)
    if match:
        return int(match.group(1)), int(match.group(2))
    match = re.fullmatch(r"[a-z_]+?_(\d+)_plus", value_id)
    if match:
        return int(match.group(1)), None
    raise HMRCISAStatisticsError(f"Unparseable ISA band id {value_id!r}.")


def _bands(value_ids: tuple[str, ...]) -> tuple[HMRCISABand, ...]:
    """Contiguous bands from published integer edges (``lo`` to ``hi`` inclusive)."""

    bands = []
    previous_high: int | None = None
    for value_id in value_ids:
        low, high = isa_band_bounds(value_id)
        if previous_high is not None and low not in (previous_high + 1, previous_high):
            raise HMRCISAStatisticsError(
                f"ISA band {value_id!r} does not continue from {previous_high}."
            )
        if low == high:
            bands.append(HMRCISABand(value_id, float(low), float(high)))
        else:
            if previous_high is not None:
                lower: float | None = float(previous_high)
            elif low == 0:
                lower = None
            else:
                lower = float(low - 1)
            upper = None if high is None else float(high)
            bands.append(HMRCISABand(value_id, lower, upper))
        previous_high = high
    return tuple(bands)


@dataclass(frozen=True)
class HMRCISAStatistics:
    """The ISA facts the subscription and Lifetime ISA stages read.

    Keys use the published value ids. Counts are individuals (Tables 9.7 to 9.9),
    accounts (Table 9.4) or pounds; nothing is aged, scaled or derived.
    """

    income_bands: tuple[HMRCISABand, ...]
    subscription_bands: tuple[HMRCISABand, ...]
    #: Table 9.7: (type, income band, subscription band) -> individuals; type in
    #: HMRC_ISA_TYPES or 'all', band ids or 'all'.
    subscribers_by_income: Mapping[tuple[str, str, str], float]
    #: Table 9.7's holders who made no further subscription: (type, income band).
    #: The all-holders column restates Table 9.10's, which the feed ports once.
    non_subscribing_holders_by_income: Mapping[tuple[str, str], float]
    #: Table 9.8: (type, sex, age band) -> individuals subscribing; age bands only,
    #: as the feed ports the all-ages totals once, in Table 9.7.
    subscribers_by_age_sex: Mapping[tuple[str, str, str], float]
    #: Table 9.9: (type, region row id) -> individuals subscribing; the regions,
    #: overseas and England (the UK total is Table 9.7's).
    subscribers_by_region: Mapping[tuple[str, str], float]
    #: Table 9.4: (component, tax year) -> accounts subscribed to / GBP subscribed.
    accounts_subscribed: Mapping[tuple[str, int], float]
    amount_subscribed: Mapping[tuple[str, int], float]
    #: Table 9.6, 2024-25: component -> market value (GBP) at 5 April 2025.
    market_value_2024: Mapping[str, float]
    #: The impact note's 2022-23 shares of under-65 cash ISA subscribers (percent).
    under_65_cash_subscriber_shares: Mapping[str, float]
    #: Lifetime ISA Table 1a: tax year -> individuals withdrawing for a house purchase.
    lisa_house_purchase_withdrawers: Mapping[int, float]
    resource_sha256: str
    source_fact_feed: Mapping[str, Any]

    def subscribers(self, isa_type: str, income: str, band: str) -> float:
        return self.subscribers_by_income[(isa_type, income, band)]

    def evidence(self) -> dict[str, object]:
        return {
            "resource": HMRC_ISA_STATISTICS_RESOURCE,
            "resource_sha256": self.resource_sha256,
            "source_commit": self.source_fact_feed.get("source_commit"),
            "individual_tax_year": HMRC_ISA_INDIVIDUAL_TAX_YEAR,
            "account_tax_years": list(HMRC_ISA_ACCOUNT_TAX_YEARS),
        }


def _load_payload(verify_feed_identity: bool) -> tuple[dict[str, Any], str]:
    payload = load_vendored_resource(HMRC_ISA_STATISTICS_RESOURCE)
    if verify_feed_identity:
        verify_vendored_resource_feed_identity(payload)
    digest = hashlib.sha256(
        files("microcosm.build.uk").joinpath(HMRC_ISA_STATISTICS_RESOURCE).read_bytes()
    ).hexdigest()
    return payload, digest


def _row_values(rows: list[Mapping[str, Any]]) -> dict[str, float]:
    values: dict[str, float] = {}
    for row in rows:
        record_id = str(row["source_record_id"])
        if record_id in values:
            raise HMRCISAStatisticsError(f"Duplicate vendored ISA fact {record_id!r}.")
        value = row.get("value")
        if not isinstance(value, (int, float)) or isinstance(value, bool):
            raise HMRCISAStatisticsError(
                f"Vendored ISA fact {record_id!r} is not numeric."
            )
        values[record_id] = float(value)
    return values


def _take(values: Mapping[str, float], record_id: str) -> float:
    try:
        return values[record_id]
    except KeyError:
        raise HMRCISAStatisticsError(
            f"The vendored ISA facts lack {record_id!r}; re-vendor from the pinned feed."
        ) from None


def check_isa_statistics_declaration(
    parameters: Mapping[str, Any], *, stage: str, period: int
) -> None:
    """The runtime arm of a stage's ``verify_vendored_fact_resource`` operation.

    The declaration names this module's resource, artifact role and record sets, and
    maps the facts to the frame's build period.
    """

    expected = {
        "artifact_role": HMRC_ISA_STATISTICS_ARTIFACT_ROLE,
        "resource": HMRC_ISA_STATISTICS_RESOURCE,
        "record_sets": list(HMRC_ISA_STATISTICS_RECORD_SETS),
        "mapped_build_period": HMRC_ISA_BUILD_TAX_YEAR,
    }
    declared = {key: parameters.get(key) for key in expected}
    if declared != expected:
        raise HMRCISAStatisticsError(
            f"{stage}'s verify_vendored_fact_resource must declare {expected}, "
            f"not {declared}."
        )
    if int(period) != HMRC_ISA_BUILD_TAX_YEAR:
        raise HMRCISAStatisticsError(
            f"{stage} maps HMRC's ISA facts to build period {HMRC_ISA_BUILD_TAX_YEAR}, "
            f"but the frame's period is {period}."
        )


def load_hmrc_isa_statistics(
    *,
    payload: Mapping[str, Any] | None = None,
    verify_feed_identity: bool = True,
) -> HMRCISAStatistics:
    """Type the vendored ISA facts, refusing any drift from the published roster.

    ``payload`` replaces the packaged resource (tests and the synthetic fixture);
    the packaged resource is checked against the committed feed pin first.
    """

    if payload is None:
        payload, digest = _load_payload(verify_feed_identity)
    else:
        if verify_feed_identity:
            verify_vendored_resource_feed_identity(payload)
        digest = "supplied"
    values = _row_values(list(payload.get("rows", ())))
    income_bands = _bands(HMRC_ISA_INCOME_BAND_IDS)
    subscription_bands = _bands(HMRC_ISA_SUBSCRIPTION_BAND_IDS)
    if not any(band.upper == 12000 for band in subscription_bands):
        raise HMRCISAStatisticsError(
            "The subscription bands lost their GBP 12,000 edge."
        )
    if not subscription_bands[-1].is_point or subscription_bands[-1].upper != 20000:
        raise HMRCISAStatisticsError(
            "The top subscription band must be exactly GBP 20,000."
        )
    tax_year = f"ty{HMRC_ISA_INDIVIDUAL_TAX_YEAR}"

    subscribers_by_income: dict[tuple[str, str, str], float] = {}
    non_subscribing: dict[tuple[str, str], float] = {}
    for isa_type in ("all", *HMRC_ISA_TYPES):
        record_set = f"{_PREFIX}table9_7.{tax_year}.{isa_type}"
        for income in (*HMRC_ISA_INCOME_BAND_IDS, "all"):
            for band in HMRC_ISA_SUBSCRIPTION_BAND_IDS:
                subscribers_by_income[(isa_type, income, band)] = _take(
                    values, f"{record_set}.subscribers.{income}.{band}"
                )
            subscribers_by_income[(isa_type, income, "all")] = _take(
                values, f"{record_set}.subscribers.{income}.all_subscriptions"
            )
            non_subscribing[(isa_type, income)] = _take(
                values, f"{record_set}.holders.{income}.no_further_subscription"
            )

    subscribers_by_age_sex: dict[tuple[str, str, str], float] = {}
    for sex in _SEXES:
        record_set = f"{_PREFIX}table9_8.{tax_year}.{sex}"
        for age in HMRC_ISA_AGE_BAND_IDS:
            for isa_type, measure in _TYPE_MEASURES.items():
                subscribers_by_age_sex[(isa_type, sex, age)] = _take(
                    values, f"{record_set}.subscribers.{age}.{measure}"
                )

    subscribers_by_region: dict[tuple[str, str], float] = {}
    for region in (*HMRC_ISA_REGION_IDS, "E92000001"):
        for isa_type, measure in _TYPE_MEASURES.items():
            subscribers_by_region[(isa_type, region)] = _take(
                values, f"{_PREFIX}table9_9.{tax_year}.subscribers.{region}.{measure}"
            )

    accounts: dict[tuple[str, int], float] = {}
    amounts: dict[tuple[str, int], float] = {}
    for year in HMRC_ISA_ACCOUNT_TAX_YEARS:
        for component in _COMPONENTS:
            accounts[(component, year)] = _take(
                values, f"{_PREFIX}table9_4.accounts.ty{year}.{component}.accounts"
            )
            amounts[(component, year)] = _take(
                values, f"{_PREFIX}table9_4.amounts.ty{year}.{component}.amounts"
            )

    market_value = {
        component: _take(
            values, f"{_PREFIX}table9_6.ty2024.{component}.all.market_value"
        )
        for component in ("stocks_and_shares", "cash", "innovative_finance", "all")
    }
    market_value["stocks_and_shares_cash_on_deposit"] = _take(
        values,
        f"{_PREFIX}table9_6.ty2024.stocks_and_shares.cash_on_deposit.market_value",
    )
    shares = {
        band: _take(values, f"{_NOTE_RECORD_SET}.{band}.share_of_cash_subscribers")
        for band in ("under_12000", "over_12000")
    }
    lisa_withdrawers = {
        year: _take(
            values,
            f"{_LISA_PREFIX}ty{year}.tax_year_{year}.house_purchase_withdrawers",
        )
        for year in (2024, 2025)
    }
    statistics = HMRCISAStatistics(
        income_bands=income_bands,
        subscription_bands=subscription_bands,
        subscribers_by_income=subscribers_by_income,
        non_subscribing_holders_by_income=non_subscribing,
        subscribers_by_age_sex=subscribers_by_age_sex,
        subscribers_by_region=subscribers_by_region,
        accounts_subscribed=accounts,
        amount_subscribed=amounts,
        market_value_2024=market_value,
        under_65_cash_subscriber_shares=shares,
        lisa_house_purchase_withdrawers=lisa_withdrawers,
        resource_sha256=digest,
        source_fact_feed=dict(payload.get("source_fact_feed", {})),
    )
    _check_published_identities(statistics)
    return statistics


def _check_published_identities(statistics: HMRCISAStatistics) -> None:
    """Refuse a resource whose own tables disagree beyond publication rounding.

    These are HMRC's identities, not reconciliations: the 'all' block is the sum of
    the type blocks, band by band and in the all-subscriptions column. The totals
    Tables 9.8 and 9.9 restate from Table 9.7 are not in the feed: Chronicle checks
    each restated copy against Table 9.7 and ports it once.
    """

    tolerance = 25.0
    cells = statistics.subscribers_by_income
    for income in (*HMRC_ISA_INCOME_BAND_IDS, "all"):
        for band in (*HMRC_ISA_SUBSCRIPTION_BAND_IDS, "all"):
            parts = sum(cells[(t, income, band)] for t in HMRC_ISA_TYPES)
            if abs(cells[("all", income, band)] - parts) > tolerance:
                raise HMRCISAStatisticsError(
                    f"Table 9.7's all block differs from its type blocks at {income}/{band}."
                )
