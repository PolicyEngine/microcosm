"""HMRC's annual savings statistics, typed from the pinned Chronicle feed (microcosm#1415).

The FRS and WAS record ISA balances and interest, not what people pay in during a
year, so a UK build that scores an ISA limit has to impute subscriptions. HMRC's
ISA tables (September 2026 release) are the only per-person evidence: Table 9.7
counts the individuals subscribing in 2023-24 by total income, size of
subscription and the types they paid into, Table 9.8 by age and sex and Table 9.9
by region. Table 9.4 gives the accounts and amounts subscribed by type to
2024-25, including the Lifetime ISA rows, which Tables 9.7 to 9.9 leave out.

Every row here is copied verbatim from the pinned Chronicle consumer feed into one
vendored resource (``hmrc_isa_statistics_facts.json``, regenerated by
``tools/vendor_uk_ledger_facts.py``). The loader types those rows, refuses a
resource that was not vendored from the committed feed pin, and refuses a roster
that has drifted from the module constants: the bands must stay contiguous, keep
their GBP 12,000 edge and their exact GBP 20,000 band.

Read the published basis before using these facts:

* Tables 9.7 to 9.12 head their columns "(thousands)" but count individuals; the
  feed carries them unscaled. Table 9.4 counts accounts, not individuals.
* Table 9.7's type blocks are the types paid into: the cash-only block plus the
  "both" block reproduce Table 9.4's 2023-24 cash accounts, and the stocks-and-
  shares-only block plus "both" its stocks-and-shares accounts. In the "both"
  block the band is the combined amount.
* Innovative Finance ISAs are excluded from Tables 9.7 to 9.12, and so are
  Lifetime ISAs (their counts are not in the cash or stocks-and-shares accounts).
* Table 9.7 has no amounts, and its bands do not reconcile with Table 9.4's
  amounts subscribed: valued at band floors, cash-only subscribers alone come to
  more than Table 9.4's cash amount. The stage keeps Table 9.7's people and uses
  Table 9.4 for ratios only (microcosm#1415, María's ruling of 28 October 2026).
"""

